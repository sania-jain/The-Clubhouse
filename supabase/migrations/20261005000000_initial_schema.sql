-- VTRisk initial schema: players, events, betting options, bets, and a
-- leaderboard view. Run this first, then supabase/seed.sql.

-- ---------- Tables ----------

create table public.profiles (
  id uuid primary key default gen_random_uuid(),
  -- Links a player to a Supabase Auth login once sign-in exists. Seeded
  -- demo players have no login, so this stays null for them.
  user_id uuid unique references auth.users (id) on delete cascade,
  username text not null unique,
  display_name text not null,
  initials text,
  detail text,                                    -- e.g. "Junior · CS"
  balance integer not null default 1000 check (balance >= 0),
  change_pct numeric(5, 1) not null default 0,    -- % change in balance this period
  points_history integer[] not null default '{}',
  created_at timestamptz not null default now()
);

create table public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  subtitle text,
  category text not null default 'General',
  tag text not null default 'UPCOMING',           -- LIVE, NEW, TRENDING, CLOSING SOON, ...
  tag_color text not null default 'secondary'
    check (tag_color in ('primary', 'secondary', 'accent')),
  starts_at timestamptz not null,
  closes_at timestamptz not null,
  volume integer not null default 0,              -- total points traded
  created_at timestamptz not null default now()
);

create table public.event_options (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events (id) on delete cascade,
  label text not null,
  probability integer not null default 50 check (probability between 0 and 100),
  change numeric(5, 1) not null default 0,        -- change in probability, in points
  prob_history integer[] not null default '{}',
  sort_order integer not null default 0,
  unique (event_id, label)
);

create index event_options_event_id_idx on public.event_options (event_id);

create table public.bets (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  option_id bigint not null references public.event_options (id) on delete cascade,
  amount integer not null check (amount > 0),
  created_at timestamptz not null default now()
);

create index bets_profile_id_idx on public.bets (profile_id);
create index bets_option_id_idx on public.bets (option_id);

-- ---------- Leaderboard ----------

-- Every player ranked by balance. security_invoker makes the view obey the
-- profiles table's row level security instead of bypassing it.
create view public.leaderboard
with (security_invoker = true) as
select
  id,
  username,
  display_name,
  initials,
  detail,
  balance as points,
  change_pct,
  points_history,
  rank() over (order by balance desc)::integer as rank
from public.profiles;

-- ---------- Row level security ----------

-- Read-only for now: anyone can read, and nothing can be inserted, updated
-- or deleted with the publishable key. Write policies (placing bets,
-- editing your own profile) get added along with sign-in.

alter table public.profiles enable row level security;
alter table public.events enable row level security;
alter table public.event_options enable row level security;
alter table public.bets enable row level security;

create policy "Anyone can read profiles" on public.profiles
  for select to anon, authenticated using (true);

create policy "Anyone can read events" on public.events
  for select to anon, authenticated using (true);

create policy "Anyone can read event options" on public.event_options
  for select to anon, authenticated using (true);

create policy "Anyone can read bets" on public.bets
  for select to anon, authenticated using (true);

grant select on
  public.profiles,
  public.events,
  public.event_options,
  public.bets,
  public.leaderboard
to anon, authenticated;
